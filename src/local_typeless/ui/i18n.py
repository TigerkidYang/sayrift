_TABLES = {"zh": _ZH, "en": _EN}
_lang = "zh"


def resolve(setting: str) -> str:
    if setting in _TABLES:
        return setting
    return "zh" if QLocale.system().language() == QLocale.Language.Chinese else "en"


def set_language(setting: str) -> None:
    global _lang
    _lang = resolve(setting)


def language() -> str:
    return _lang


def tr(key: str, **kw: object) -> str:
    text = _TABLES[_lang].get(key) or _EN.get(key, key)
    return text.format(**kw) if kw else text
